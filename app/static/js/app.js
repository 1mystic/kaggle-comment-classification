const CLASS_ORDER = ["Normal", "Offensive", "Hate Speech", "Severe/Violent"];
const RISK_BY_LABEL = {
  "Normal": "low",
  "Offensive": "moderate",
  "Hate Speech": "high",
  "Severe/Violent": "high",
};

const PRESETS = {
  normal: {
    comment: "Awesome article! Thanks for sharing this useful explanation, really appreciate it.",
    if_1: 0, if_2: 2, upvotes: 15, downvotes: 0, race: "none", religion: "none", gender: "none",
  },
  offensive: {
    comment: "This post is complete garbage and your opinion is dumb.",
    if_1: 0, if_2: 8, upvotes: 2, downvotes: 5, race: "none", religion: "none", gender: "none",
  },
  hate: {
    comment: "I hate these people, they are terrible and should be kicked out.",
    if_1: 4, if_2: 10, upvotes: 0, downvotes: 12, race: "Black", religion: "Muslim", gender: "none",
  },
  violent: {
    comment: "I will k1ll you and shoot your family d34d.",
    if_1: 0, if_2: 12, upvotes: 0, downvotes: 0, race: "none", religion: "none", gender: "none",
  },
};

const el = (id) => document.getElementById(id);
let currentDecisionId = null;
const DAY_NAMES = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];

function initTabs() {
  document.querySelectorAll(".tab-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      document.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("is-active"));
      document.querySelectorAll(".view").forEach((v) => v.classList.remove("is-active"));
      btn.classList.add("is-active");
      el(`view-${btn.dataset.view}`).classList.add("is-active");
      if (btn.dataset.view === "audit") loadAuditLog();
    });
  });
}

function initSliders() {
  el("if1").addEventListener("input", (e) => (el("if1Val").textContent = e.target.value));
  el("if2").addEventListener("input", (e) => (el("if2Val").textContent = e.target.value));
}

function applyPreset(name) {
  const p = PRESETS[name];
  if (!p) return;
  el("commentInput").value = p.comment;
  el("if1").value = p.if_1; el("if1Val").textContent = p.if_1;
  el("if2").value = p.if_2; el("if2Val").textContent = p.if_2;
  el("upvotes").value = p.upvotes;
  el("downvotes").value = p.downvotes;
  el("race").value = p.race;
  el("religion").value = p.religion;
  el("gender").value = p.gender;
}

function initPresets() {
  document.querySelectorAll(".btn-preset").forEach((btn) => {
    btn.addEventListener("click", () => applyPreset(btn.dataset.preset));
  });
}

async function checkHealth() {
  const pill = el("modelStatusPill");
  try {
    const res = await fetch("/api/health");
    const data = await res.json();
    pill.textContent = data.model_active ? "Model active" : "Demo mode (no model)";
    pill.className = "pill " + (data.model_active ? "pill-active" : "pill-demo");
  } catch (e) {
    pill.textContent = "Offline";
    pill.className = "pill pill-demo";
  }
}

function renderProbBars(confidences) {
  const container = el("probBars");
  container.innerHTML = "";
  const sorted = [...CLASS_ORDER].sort((a, b) => confidences[b] - confidences[a]);
  sorted.forEach((label) => {
    const pct = (confidences[label] * 100).toFixed(1);
    const risk = RISK_BY_LABEL[label];
    const row = document.createElement("div");
    row.className = "prob-row";
    row.innerHTML = `
      <span>${label}</span>
      <span class="prob-track"><span class="prob-fill risk-${risk}" style="width:${pct}%"></span></span>
      <span>${pct}%</span>
    `;
    container.appendChild(row);
  });
}

function renderResult(result) {
  el("heroLabel").textContent = result.label;
  el("heroConfidence").textContent = `${(result.confidence * 100).toFixed(1)}% confidence`;

  const badge = el("riskBadge");
  badge.className = "badge risk-" + result.risk_level;
  badge.textContent =
    result.risk_level === "high" ? "High risk - action required" :
    result.risk_level === "moderate" ? "Moderate risk" : "Low risk / safe";

  renderProbBars(result.confidences);

  el("sentimentVal").textContent = result.sentiment_score.toFixed(1);
  el("capsVal").textContent = result.caps_ratio.toFixed(1) + "%";

  const terms = [];
  if (result.violence_terms.length) terms.push(`<strong>Violent terms:</strong> ${result.violence_terms.join(", ")}`);
  if (result.negative_terms.length) terms.push(`<strong>Negative terms:</strong> ${result.negative_terms.join(", ")}`);
  if (result.positive_terms.length) terms.push(`<strong>Positive terms:</strong> ${result.positive_terms.join(", ")}`);
  el("termsOut").innerHTML = terms.length ? terms.join("<br>") : "Standard vocabulary - no flagged terms.";

  if (result.explanation) {
    el("explanationCard").style.display = "block";
    el("citationBadge").textContent = result.explanation.policy_citation || "No citation";
    el("explanationText").textContent = result.explanation.explanation;
    el("explanationSource").textContent =
      result.explanation.source === "llm" ? "Generated by Claude, grounded in policy" : "Template-generated (no LLM configured)";
  }

  if (result.agent) {
    currentDecisionId = result.agent.decision_id;
    el("agentCard").style.display = "block";
    const badge = el("agentStatusBadge");
    badge.className = "badge risk-" + result.risk_level;
    badge.textContent = result.agent.agent_status_label;
    el("appealReason").value = "";
    el("appealResult").textContent = "";

    const overrideEl = el("overrideNote");
    if (result.agent.override_reason) {
      overrideEl.style.display = "block";
      overrideEl.textContent = "⚠ " + result.agent.override_reason;
    } else {
      overrideEl.style.display = "none";
    }
  }
}

async function submitAppeal() {
  const reason = el("appealReason").value.trim();
  if (!reason || currentDecisionId == null) return;
  const btn = el("appealBtn");
  btn.disabled = true;
  btn.textContent = "Reviewing…";
  try {
    const res = await fetch(`/api/appeal/${currentDecisionId}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ reason }),
    });
    if (!res.ok) throw new Error(`Request failed: ${res.status}`);
    const result = await res.json();
    el("appealResult").textContent = result.explanation.explanation;
  } catch (e) {
    el("appealResult").textContent = "Appeal could not be processed.";
    console.error(e);
  } finally {
    btn.disabled = false;
    btn.textContent = "Appeal this decision";
  }
}

function renderHeatmap(heatmapData) {
  const container = el("heatmap");
  container.innerHTML = "";
  const counts = {};
  let maxCount = 1;
  heatmapData.forEach((d) => {
    counts[`${d.day}-${d.hour}`] = d.count;
    maxCount = Math.max(maxCount, d.count);
  });

  // Header row: blank corner + 24 hour labels (every 4th hour shown)
  container.appendChild(document.createElement("div"));
  for (let h = 0; h < 24; h++) {
    const label = document.createElement("div");
    label.style.fontSize = "9px";
    label.textContent = h % 4 === 0 ? h : "";
    container.appendChild(label);
  }

  for (let day = 0; day < 7; day++) {
    const dayLabel = document.createElement("div");
    dayLabel.className = "heatmap-daylabel";
    dayLabel.textContent = DAY_NAMES[day];
    container.appendChild(dayLabel);

    for (let hour = 0; hour < 24; hour++) {
      const count = counts[`${day}-${hour}`] || 0;
      const cell = document.createElement("div");
      cell.className = "heatmap-cell";
      cell.title = `${DAY_NAMES[day]} ${hour}:00 - ${count} decision(s)`;
      if (count > 0) {
        const intensity = Math.min(1, count / maxCount);
        cell.style.background = `rgba(79, 70, 229, ${0.15 + intensity * 0.7})`;
        cell.style.borderColor = "transparent";
      }
      container.appendChild(cell);
    }
  }
}

function renderRecentList(recent) {
  const container = el("recentList");
  if (!recent.length) {
    container.innerHTML = '<p class="muted">No decisions logged yet - analyze a comment to populate this log.</p>';
    return;
  }
  container.innerHTML = "";
  recent.forEach((d) => {
    const row = document.createElement("div");
    row.className = "recent-row";
    const excerpt = d.comment_text.length > 60 ? d.comment_text.slice(0, 60) + "…" : d.comment_text;
    const risk = RISK_BY_LABEL[d.label] || "low";
    row.innerHTML = `
      <span class="badge risk-${risk}">${d.label}</span>
      <span class="excerpt">${excerpt}</span>
      <span class="meta">${d.agent_status} · ${new Date(d.created_at).toLocaleString()}</span>
    `;
    container.appendChild(row);
  });
}

const DRIFT_LABELS = {
  healthy: "Healthy",
  watch: "Watch - moderate drift",
  drift_detected: "Drift detected",
  insufficient_data: "Insufficient data",
};
const DRIFT_RISK = {
  healthy: "low",
  watch: "moderate",
  drift_detected: "high",
  insufficient_data: "low",
};

function renderDistBars(baseline, live) {
  const container = el("distBars");
  container.innerHTML = "";
  CLASS_ORDER.forEach((label) => {
    const basePct = (baseline[label] * 100).toFixed(1);
    const livePct = ((live[label] || 0) * 100).toFixed(1);
    const risk = RISK_BY_LABEL[label];
    const row = document.createElement("div");
    row.className = "prob-row";
    row.innerHTML = `
      <span>${label}</span>
      <span class="prob-track"><span class="prob-fill risk-${risk}" style="width:${livePct}%"></span></span>
      <span class="dist-label">${livePct}% live / ${basePct}% baseline</span>
    `;
    container.appendChild(row);
  });
}

async function loadModelHealth() {
  try {
    const res = await fetch("/api/monitoring");
    const data = await res.json();
    const badge = el("driftBadge");
    badge.className = "badge risk-" + DRIFT_RISK[data.drift_status];
    badge.textContent = `${DRIFT_LABELS[data.drift_status]} (PSI ${data.psi})`;
    el("healthAvgConf").textContent = data.avg_confidence.toFixed(1) + "%";
    el("healthAppealRate").textContent = data.appeal_rate.toFixed(1) + "%";
    renderDistBars(data.baseline_distribution, data.live_distribution);
  } catch (e) {
    console.error(e);
  }
}

async function loadAuditLog() {
  try {
    const res = await fetch("/api/audit");
    const data = await res.json();
    el("statTotal").textContent = data.stats.total_decisions;
    el("statAutoActioned").textContent = data.stats.pct_auto_actioned.toFixed(0) + "%";
    el("statAvgConfidence").textContent = data.stats.avg_confidence.toFixed(1) + "%";
    renderHeatmap(data.heatmap);
    renderRecentList(data.recent);
  } catch (e) {
    console.error(e);
  }
  loadModelHealth();
}

async function analyze() {
  const comment = el("commentInput").value.trim();
  if (!comment) {
    el("heroConfidence").textContent = "Please enter a comment to analyze.";
    return;
  }
  const btn = el("analyzeBtn");
  btn.disabled = true;
  btn.textContent = "Analyzing…";
  try {
    const res = await fetch("/api/analyze", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        comment,
        if_1: Number(el("if1").value),
        if_2: Number(el("if2").value),
        upvotes: Number(el("upvotes").value),
        downvotes: Number(el("downvotes").value),
        race: el("race").value,
        religion: el("religion").value,
        gender: el("gender").value,
      }),
    });
    if (!res.ok) throw new Error(`Request failed: ${res.status}`);
    const result = await res.json();
    renderResult(result);
  } catch (e) {
    el("heroConfidence").textContent = "Something went wrong analyzing this comment.";
    console.error(e);
  } finally {
    btn.disabled = false;
    btn.textContent = "Analyze comment safety";
  }
}

function init() {
  initTabs();
  initSliders();
  initPresets();
  el("analyzeBtn").addEventListener("click", analyze);
  el("appealBtn").addEventListener("click", submitAppeal);
  checkHealth();
}

document.addEventListener("DOMContentLoaded", init);
